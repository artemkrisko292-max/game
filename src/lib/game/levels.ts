/** Строитель ASCII-карт: гарантирует одинаковую длину строк. */
class MapBuilder {
  private g: string[][]

  constructor(
    rows: number,
    private cols: number,
  ) {
    this.g = Array.from({ length: rows }, () => Array<string>(cols).fill('.'))
  }

  set(r: number, c: number, ch: string): this {
    if (r >= 0 && r < this.g.length && c >= 0 && c < this.cols) {
      this.g[r][c] = ch
    }
    return this
  }

  /** Горизонтальная платформа из твёрдых блоков, cols включительно. */
  plat(r: number, c0: number, c1: number): this {
    for (let c = c0; c <= c1; c++) this.set(r, c, '#')
    return this
  }

  /** Двойной пол в двух нижних строках. */
  ground(c0 = 0, c1 = this.cols - 1): this {
    const rows = this.g.length
    for (let c = c0; c <= c1; c++) {
      this.set(rows - 1, c, '#')
      this.set(rows - 2, c, '#')
    }
    return this
  }

  /** Люк в полу (проваливаешься — теряешь энергию). */
  pit(c0: number, c1: number): this {
    const rows = this.g.length
    for (let c = c0; c <= c1; c++) {
      this.set(rows - 1, c, '.')
      this.set(rows - 2, c, '.')
    }
    return this
  }

  build(): string[] {
    return this.g.map((row) => row.join(''))
  }
}

