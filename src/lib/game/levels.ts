// Уровни игры «ЭнергоГерой».
// Первые три уровня заданы ASCII-сеткой, остальные собраны MapBuilder-ом
// (размер клетки 40px, сетка 14 строк).
//
// Легенда:
//   #  — твёрдый блок (пол / платформа)
//   P  — точка появления игрока (Вжика)
//   B  — LED-лампочка (коллекционный предмет: +энергия, +очки)
//   L  — висячая лампа, группа A (жрёт энергию конусом света вниз)
//   M  — висячая лампа, группа B
//   S  — рубильник группы A (выключает лампы A)
//   T  — рубильник группы B
//   V  — ЭнергоВампир (ходит по земле, туда-сюда)
//   F  — Фантом (парит сквозь стены, «фантомная нагрузка»)
//   G  — Гонец (быстрый огненный спринтер, бьёт сильнее всех)
//   Z  — Дрон-пылесос (летает по диагонали, отскакивая от стен)
//   X  — искрящая сломанная розетка (опасность)
//   ^  — шипы из старой арматуры (опасность)
//   C  — осыпающаяся плита (рассыпается через полсекунды под игроком)
//   W  — движущаяся платформа (горизонтальная)
//   U  — движущаяся платформа (вертикальная)
//   K  — предохранитель (снимает замок с выхода)
//   E  — выход (электрический щиток; с предохранителями — заперт)

